"""Seeded generator of small synthetic scheduling instances for Phase 3.

Each instance has 8 to 12 tasks, a fixed seed and a named dependency shape.
Every instance uses the same four-column CSV format as tasks.csv, needs at
most 2 workers per task, and is checked with load_tasks before it is written.
Running the generator twice gives byte-identical files.

Usage:
    python -m experiments.heuristic_data            (writes heuristic_test_data/)

Standard library only. File names come from the fixed INSTANCES table below;
nothing user-supplied is used in a file name or passed to a shell.
"""
import csv
import os
import random

from scheduling.data_validation import load_tasks

CAPACITY = 2
MIN_TASKS = 8
MAX_TASKS = 12
DEFAULT_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'data', 'heuristic_test_data')

# (file name, shape, seed, task count)
INSTANCES = (
    ('wide_01.csv', 'wide', 101, 9),
    ('wide_02.csv', 'wide', 102, 11),
    ('deep_01.csv', 'deep', 201, 8),
    ('deep_02.csv', 'deep', 202, 10),
    ('mixed_01.csv', 'mixed', 301, 10),
    ('mixed_02.csv', 'mixed', 302, 12),
)

RULES = {
    'wide': 'T01 is the only root; the middle tasks all depend on T01 (wide fan-out); '
            'the last task joins every middle task.',
    'deep': 'A chain: each task depends on the previous one; about one task in three also '
            'depends on a task two or three steps back.',
    'mixed': 'Three layers of similar size; each task depends on 1 to 2 random tasks of the '
             'previous layer; layer 1 has no prerequisites.',
}


def _ids(count):
    return ['T%02d' % (i + 1) for i in range(count)]


def _duration_and_workers(rng):
    """Durations 1 to 5. About one task in five needs 2 workers, the rest need 1."""
    duration = rng.randint(1, 5)
    workers = 2 if rng.random() < 0.2 else 1
    return duration, workers


def _dependencies(shape, count, rng):
    """Return a list of dependency lists (by index). Dependencies only point backwards."""
    deps = [[] for _ in range(count)]
    if shape == 'wide':
        for i in range(1, count - 1):
            deps[i] = [0]
        deps[count - 1] = list(range(1, count - 1))
    elif shape == 'deep':
        for i in range(1, count):
            deps[i] = [i - 1]
            if i >= 3 and rng.random() < 0.33:
                extra = i - rng.randint(2, 3)
                if extra not in deps[i]:
                    deps[i].append(extra)
    elif shape == 'mixed':
        size = count // 3
        layers = [list(range(0, size)),
                  list(range(size, 2 * size)),
                  list(range(2 * size, count))]
        for layer in (1, 2):
            previous = layers[layer - 1]
            for i in layers[layer]:
                picks = rng.sample(previous, min(len(previous), rng.randint(1, 2)))
                deps[i] = sorted(picks)
    else:
        raise ValueError('unknown shape: %s' % shape)
    return deps


def generate_rows(shape, seed, count):
    """Return the CSV rows (without header) for one instance. Uses its own Random(seed)."""
    if not MIN_TASKS <= count <= MAX_TASKS:
        raise ValueError('task count must be %d to %d' % (MIN_TASKS, MAX_TASKS))
    rng = random.Random(seed)
    ids = _ids(count)
    deps = _dependencies(shape, count, rng)
    rows = []
    for i in range(count):
        duration, workers = _duration_and_workers(rng)
        dep_text = ', '.join(ids[d] for d in sorted(deps[i])) if deps[i] else 'None'
        rows.append([ids[i], duration, dep_text, workers])
    return rows


def _write_csv(path, rows):
    with open(path, 'w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f, lineterminator='\n')
        writer.writerow(['task_id', 'duration', 'depends_on', 'workers_required'])
        writer.writerows(rows)


def _notes_text():
    lines = [
        '# Heuristic test data',
        '',
        'Generated by `heuristic_data.py`. Do not edit by hand; rerun the generator.',
        'Each file uses the tasks.csv format, has 8 to 12 tasks, and needs at most 2 workers',
        'per task (capacity 2). Each file has its own `random.Random(seed)`.',
        'Durations are 1 to 5 days; about 1 task in 5 needs 2 workers.',
        '',
        '| File | Shape | Seed | Tasks |',
        '|---|---|---|---|',
    ]
    for name, shape, seed, count in INSTANCES:
        lines.append('| %s | %s | %d | %d |' % (name, shape, seed, count))
    lines += ['', '## Generation rules', '']
    for shape, rule in RULES.items():
        lines.append('- **%s**: %s' % (shape, rule))
    lines.append('')
    return '\n'.join(lines)


def generate_all(out_dir=DEFAULT_DIR):
    """Write every instance and NOTES.md into out_dir. Returns the list of CSV paths."""
    out_dir = os.path.abspath(str(out_dir))
    os.makedirs(out_dir, exist_ok=True)
    paths = []
    for name, shape, seed, count in INSTANCES:
        path = os.path.join(out_dir, name)
        _write_csv(path, generate_rows(shape, seed, count))
        load_tasks(path, CAPACITY)  # fail loudly if an instance is invalid
        paths.append(path)
    with open(os.path.join(out_dir, 'NOTES.md'), 'w', encoding='utf-8', newline='') as f:
        f.write(_notes_text())
    return paths


def main():
    for path in generate_all():
        print('wrote', path)


if __name__ == '__main__':
    main()
